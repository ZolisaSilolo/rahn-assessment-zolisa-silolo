"""Publish the staff web app to the private S3 bucket behind CloudFront.

Reads the stack outputs, writes config.js (public identifiers only: no secrets), uploads the files
with correct content types and cache headers, then invalidates CloudFront.

    python aws/deploy_frontend.py [--stack fitdesk-enquiry-assistant] [--region us-east-1]
"""

import argparse
import json
import mimetypes
import sys
import time
from pathlib import Path

import boto3

FRONTEND = Path(__file__).resolve().parent / "frontend"
FILES = ("index.html", "app.js", "sigv4.js", "styles.css")
NO_CACHE = "no-cache, max-age=0, must-revalidate"  # always revalidate (files are not content-hashed)


def main() -> int:
    ap = argparse.ArgumentParser()
    ap.add_argument("--stack", default="fitdesk-enquiry-assistant")
    ap.add_argument("--region", default="us-east-1")
    args = ap.parse_args()

    cfn = boto3.client("cloudformation", region_name=args.region)
    outputs = {o["OutputKey"]: o["OutputValue"] for o in cfn.describe_stacks(StackName=args.stack)["Stacks"][0]["Outputs"]}
    config = {
        "region": args.region,
        "apiUrl": outputs["FunctionUrl"],
        "userPoolId": outputs["UserPoolId"],
        "clientId": outputs["UserPoolClientId"],
        "identityPoolId": outputs["IdentityPoolId"],
        "cognitoDomain": outputs["CognitoDomain"],
    }
    config_js = "// Generated by aws/deploy_frontend.py from stack outputs. Public identifiers only.\n" \
                f"export default {json.dumps(config, indent=2)};\n"

    s3 = boto3.client("s3", region_name=args.region)
    bucket = outputs["FrontendBucketName"]
    uploads = [(name, (FRONTEND / name).read_bytes()) for name in FILES] + [("config.js", config_js.encode("utf-8"))]
    for key, body in uploads:
        content_type = mimetypes.guess_type(key)[0] or "application/octet-stream"
        if key.endswith(".js"):
            content_type = "text/javascript"
        s3.put_object(Bucket=bucket, Key=key, Body=body, ContentType=f"{content_type}; charset=utf-8",
                      CacheControl=NO_CACHE)
        print(f"uploaded s3://{bucket}/{key}")

    cloudfront = boto3.client("cloudfront")
    inv = cloudfront.create_invalidation(
        DistributionId=outputs["FrontendDistributionId"],
        InvalidationBatch={"Paths": {"Quantity": 1, "Items": ["/*"]}, "CallerReference": str(time.time())},
    )
    print(f"invalidation {inv['Invalidation']['Id']} started")
    print(f"Staff web app: {outputs['FrontendUrl']}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
